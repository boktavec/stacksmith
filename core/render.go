package core

import (
	"strings"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclsyntax"
	"github.com/hashicorp/hcl/v2/hclwrite"
	"github.com/zclconf/go-cty/cty"
)

// awsProviderVersion is the exact hashicorp/aws version the generated root is
// tested with. The bundled module keeps its looser "~> 5.0" constraint.
const awsProviderVersion = "5.100.0"

const (
	moduleSource       = "./modules/s3"
	moduleLabel        = "bucket"
	callerIdentityType = "aws_caller_identity"
)

// renderRoot builds the four Terraform root files for one resolved bucket.
// Every value enters through cty typed values, which hclwrite escapes, and
// every reference is an hcl.Traversal; no input is spliced into HCL source.
// Output order and attribute order are fixed by the code below, so the result
// is byte-stable for equal input.
func renderRoot(r resolved) []File {
	return []File{
		{Path: "versions.tf", Content: renderVersions(r)},
		{Path: "providers.tf", Content: renderProviders(r)},
		{Path: "main.tf", Content: renderMain(r)},
		{Path: "outputs.tf", Content: renderOutputs(r)},
	}
}

// newFile returns an hclwrite file whose body already holds the standard
// header: version and module ID only, no timestamps or machine data.
func newFile(r resolved) (*hclwrite.File, *hclwrite.Body) {
	f := hclwrite.NewEmptyFile()
	body := f.Body()
	body.AppendUnstructuredTokens(hclwrite.Tokens{
		commentToken("# Generated by StackSmith " + generatorVersion + " (module " + headerSafe(r.Module) + "). Review before use.\n"),
		commentToken("# Do not apply a regenerated copy as a second state for the same bucket.\n"),
	})
	body.AppendNewline()
	return f, body
}

// headerSafe keeps a value on one comment line. Validate only allows
// s3-private/v1 today; this guards the header if that ever widens.
func headerSafe(s string) string {
	return strings.NewReplacer("\n", " ", "\r", " ").Replace(s)
}

func commentToken(text string) *hclwrite.Token {
	return &hclwrite.Token{Type: hclsyntax.TokenComment, Bytes: []byte(text)}
}

func finish(f *hclwrite.File) []byte {
	return hclwrite.Format(f.Bytes())
}

func renderVersions(r resolved) []byte {
	f, body := newFile(r)
	terraform := body.AppendNewBlock("terraform", nil).Body()
	terraform.SetAttributeValue("required_version", cty.StringVal(">= 1.7.0"))
	terraform.AppendNewline()
	providers := terraform.AppendNewBlock("required_providers", nil).Body()
	providers.SetAttributeValue("aws", cty.ObjectVal(map[string]cty.Value{
		"source":  cty.StringVal("hashicorp/aws"),
		"version": cty.StringVal(awsProviderVersion),
	}))
	return finish(f)
}

func renderProviders(r resolved) []byte {
	f, body := newFile(r)
	provider := body.AppendNewBlock("provider", []string{"aws"}).Body()
	provider.SetAttributeValue("region", cty.StringVal(r.Region))
	provider.SetAttributeValue("allowed_account_ids", cty.ListVal([]cty.Value{cty.StringVal(r.AccountID)}))
	body.AppendNewline()
	body.AppendNewBlock("data", []string{callerIdentityType, "current"})
	return finish(f)
}

func renderMain(r resolved) []byte {
	f, body := newFile(r)
	module := body.AppendNewBlock("module", []string{moduleLabel}).Body()
	module.SetAttributeValue("source", cty.StringVal(moduleSource))
	module.AppendNewline()
	module.SetAttributeValue("bucket_name", cty.StringVal(r.BucketName))
	module.SetAttributeValue("name", cty.StringVal(r.LogicalName))
	module.SetAttributeValue("environment", cty.StringVal(r.Environment))
	module.SetAttributeValue("owner", cty.StringVal(r.Owner))
	module.SetAttributeValue("noncurrent_version_expiration_days", cty.NumberIntVal(int64(r.NoncurrentVersionExpirationDays)))
	return finish(f)
}

func renderOutputs(r resolved) []byte {
	f, body := newFile(r)

	arn := body.AppendNewBlock("output", []string{"bucket_arn"}).Body()
	arn.SetAttributeValue("description", cty.StringVal("The bucket's ARN."))
	arn.SetAttributeTraversal("value", moduleOutput("bucket_arn"))
	body.AppendNewline()

	name := body.AppendNewBlock("output", []string{"bucket_name"}).Body()
	name.SetAttributeValue("description", cty.StringVal("The bucket's actual AWS name."))
	name.SetAttributeTraversal("value", moduleOutput("bucket_name"))
	name.AppendNewline()
	// Terraform allows precondition directly in an output block; the
	// lifecycle wrapper is only for resources and data sources.
	precondition := name.AppendNewBlock("precondition", nil).Body()
	// hclwrite has no operator builder, so the comparison is assembled from
	// typed token streams: a traversal, "==", and an escaped string value.
	condition := hclwrite.TokensForTraversal(hcl.Traversal{
		hcl.TraverseRoot{Name: "data"},
		hcl.TraverseAttr{Name: callerIdentityType},
		hcl.TraverseAttr{Name: "current"},
		hcl.TraverseAttr{Name: "account_id"},
	})
	condition = append(condition, &hclwrite.Token{Type: hclsyntax.TokenEqualOp, Bytes: []byte("==")})
	condition = append(condition, hclwrite.TokensForValue(cty.StringVal(r.AccountID))...)
	precondition.SetAttributeRaw("condition", condition)
	precondition.SetAttributeValue("error_message", cty.StringVal(
		"The AWS credentials in use do not belong to the account this root was generated for."))
	return finish(f)
}

func moduleOutput(attr string) hcl.Traversal {
	return hcl.Traversal{
		hcl.TraverseRoot{Name: "module"},
		hcl.TraverseAttr{Name: moduleLabel},
		hcl.TraverseAttr{Name: attr},
	}
}
